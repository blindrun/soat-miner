#!/usr/bin/env python3
"""Embed CUDA headers as string literals for NVRTC.

NVRTC has no filesystem: a runtime-compiled kernel cannot `#include` our
headers from disk, and a shipped binary must not depend on its source tree
being present. So the headers travel inside the binary.

The alternative - writing the device functions out again as a string in the
generator - would be a second definition of keccak, fnv1a and the mix
primitives, drifting silently from the ones the interpreted kernel uses. Two
implementations of a hash function is how a miner produces shares that are
confidently wrong. This keeps one definition.

Three things this does that are not obvious, each of which was a failed
compile before it was a line of code:

1.  **A `stdint.h` stub is prepended.** NVRTC ships no C library, and our
    headers want fixed-width integer types.

2.  **Include spellings are canonicalised.** NVRTC matches in-memory headers by
    EXACT name and does not resolve relative paths, so `#include
    "../progpow/keccak.h"` finds nothing unless a header is registered under
    that exact spelling. Registering the same text under two spellings is not a
    fix: `#pragma once` is per-path, so it gets included twice and every
    function is redefined.

3.  **Names are given explicitly, not derived from the path.** Both mine.cuh
    files share a basename. Deriving the include name from the filename makes
    them collide, and the failure is silent - NVRTC resolves both includes to
    whichever text was registered last, and the kernel still compiles, built
    against the wrong mix function.

Usage: embed_headers.py OUT.cpp NAME=path [NAME=path ...]
"""
import sys

# NVRTC has no C library. Our device headers need only fixed-width types.
STDINT_STUB = """#pragma once
typedef unsigned char uint8_t;
typedef signed char int8_t;
typedef unsigned short uint16_t;
typedef short int16_t;
typedef unsigned int uint32_t;
typedef int int32_t;
typedef unsigned long long uint64_t;
typedef long long int64_t;
typedef unsigned long size_t;
"""

# Real include spelling -> the name that header is registered under. Both
# mine.cuh files are here precisely because their basenames collide.
CANON = {
    '"../progpow/keccak.h"': '"keccak.h"',
    '"../progpow/ethash.h"': '"ethash.h"',
    '"../progpow/progpow.h"': '"progpow.h"',
    '"../progpow/mine.cuh"': '"progpow_mine.cuh"',
}


def literal(text: str) -> str:
    # A raw string needs a delimiter the content cannot contain. Pick one and
    # assert rather than hope: a header containing the delimiter would silently
    # truncate the embedded source.
    for delim in ("NVRTC", "NVRTC1", "NVRTC2", "SOATHDR"):
        if f'){delim}"' not in text:
            return f'R"{delim}({text}){delim}"'
    raise SystemExit("no safe raw-string delimiter for this header")


def canonicalise(body: str, path: str) -> str:
    for real, registered in CANON.items():
        body = body.replace(real, registered)
    # An include of a path we do not register would fail at NVRTC compile time
    # with a message naming a file, which is a slow way to find a missing entry
    # in the table above. Catch it here instead.
    for line in body.splitlines():
        stripped = line.strip()
        if stripped.startswith("#include") and "/" in stripped:
            raise SystemExit(
                f"{path}: unresolved relative include {stripped!r}\n"
                "NVRTC cannot resolve paths; add it to CANON and register the "
                "header under the canonical name."
            )
    return body


def main() -> None:
    if len(sys.argv) < 3:
        raise SystemExit(__doc__)
    out, pairs = sys.argv[1], sys.argv[2:]

    entries = [("stdint.h", "Stdint", STDINT_STUB)]
    for pair in pairs:
        name, _, path = pair.partition("=")
        if not path:
            raise SystemExit(f"expected NAME=path, got {pair!r}")
        with open(path, encoding="utf-8") as fh:
            body = canonicalise(fh.read(), path)
        entries.append((name, name.replace(".", "_").replace("/", "_"), body))

    seen = set()
    for include_name, _, _ in entries:
        if include_name in seen:
            raise SystemExit(
                f"duplicate header name {include_name!r}: two headers "
                "registered under one name compile silently against the wrong "
                "one"
            )
        seen.add(include_name)

    chunks = [
        "// GENERATED by scripts/embed_headers.py - do not edit.\n",
        '#include "../src/algos/kawpow/nvrtc_headers.h"\n\n',
        "namespace om {\nnamespace kawpow {\n\n",
    ]
    for _, ident, body in entries:
        chunks.append(f"static const char *k{ident}Src =\n{literal(body)};\n\n")

    chunks.append("const NvrtcHeader *nvrtcHeaders(int *count) {\n")
    chunks.append("    static const NvrtcHeader kAll[] = {\n")
    for include_name, ident, _ in entries:
        chunks.append(f'        {{"{include_name}", k{ident}Src}},\n')
    chunks.append("    };\n")
    chunks.append("    *count = (int)(sizeof(kAll) / sizeof(kAll[0]));\n")
    chunks.append("    return kAll;\n}\n\n")
    chunks.append("}  // namespace kawpow\n}  // namespace om\n")

    with open(out, "w", encoding="utf-8") as fh:
        fh.write("".join(chunks))
    print(f"embedded {len(entries)} headers into {out}")


if __name__ == "__main__":
    main()
