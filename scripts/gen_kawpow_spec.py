#!/usr/bin/env python3
r"""Derives the specialisation-constant KawPow shader from the verified one.

    python3 scripts/gen_kawpow_spec.py > src/algos/kawpow/kernel_spec.comp

Why derive rather than write
----------------------------
src/algos/kawpow/kernel.comp is checked against the host reference nonce for
nonce. The fast shader differs from it in exactly two places - where the
program comes from, and how the round's operations are written - and in nothing
else. Generating it means the Keccak wrappers, the KISS99 seeding, the DAG
addressing, the reduction, the target compare and the output layout are the
SAME TEXT, so the only thing a reviewer has to check is the substitution, and
the only thing that can drift is nothing.

What the substitution does
--------------------------
The program's 131 values become specialisation constants, which the driver
folds at pipeline-creation time. That turns `mix[prog.mathDst[i]]` - a dynamic
index into a local array, and the GLSL trap that cost this repository a 75x
slowdown in Blake2b - into `mix[7]`, which stays in a register. The 33
operations of a round are emitted as straight-line code for the same reason: a
loop over them would reintroduce the dynamic index.

The pipeline is rebuilt when the 3-block period turns, roughly every three
minutes on Ravencoin, which is what pays for this.

Measured on a 4090 before this existed: 1.69 MH/s on Vulkan, against 11.9 on
CUDA with the same interpreted approach and 60.3 on CUDA with the program baked
in.
"""
import re
import sys

SRC = "src/algos/kawpow/kernel.comp"

# constant_id 0 and 1 are the workgroup size and MAX_OUT, so the program starts
# clear of them.
FIRST_ID = 10

# (name, count) in the order the host uploads them, which is also the order
# src/algos/progpow/progpow.h declares them.
TABLES = [
    ("CSRC", 11), ("CDST", 11), ("CSEL", 11),
    ("MSRC1", 18), ("MSRC2", 18), ("MSEL1", 18), ("MDST", 18), ("MSEL2", 18),
    ("DDST", 4), ("DSEL", 4),
]


def declarations():
    out = []
    cid = FIRST_ID
    out.append("// The period's program, folded in at pipeline-creation time.")
    out.append("// Generated by scripts/gen_kawpow_spec.py - do not edit.")
    for name, count in TABLES:
        for i in range(count):
            out.append(f"layout(constant_id = {cid}) const uint {name}{i} = 0u;")
            cid += 1
    assert cid - FIRST_ID == 131, "the host uploads 131 values"
    return "\n".join(out)


def round_body():
    out = []
    out.append("        // One round, straight-line. A loop here would put the")
    out.append("        // destination index back at runtime and undo the point.")
    for i in range(18):
        if i < 11:
            out.append(f"        {{ const uint o = mix[CSRC{i}] % L1_WORDS;")
            out.append(f"          randomMerge(mix[CDST{i}], l1[o], CSEL{i}); }}")
        out.append(f"        {{ const uint t = randomMath(mix[MSRC1{i}], "
                   f"mix[MSRC2{i}], MSEL1{i});")
        out.append(f"          randomMerge(mix[MDST{i}], t, MSEL2{i}); }}")
    for i in range(4):
        out.append(f"        randomMerge(mix[DDST{i}], d[{i}], DSEL{i});")
    return "\n".join(out)


def main():
    text = open(SRC).read()

    # 1. The program storage buffer becomes specialisation constants.
    prog_block = re.search(
        r"layout\(std430, binding = 0\) readonly buffer Prog \{.*?\} prog;\n",
        text, re.S)
    if not prog_block:
        sys.exit("could not find the Prog block in " + SRC)
    text = text.replace(prog_block.group(0), declarations() + "\n")

    # 2. The interpreted round loop becomes straight-line code.
    loop = re.search(
        r"        for \(int i = 0; i < 18; i\+\+\) \{.*?"
        r"            randomMerge\(mix\[prog\.dagDst\[i\]\], d\[i\], prog\.dagSel\[i\]\);\n",
        text, re.S)
    if not loop:
        sys.exit("could not find the interpreted round loop in " + SRC)
    text = text.replace(loop.group(0), round_body() + "\n")

    # 3. Bindings shift down by one now that binding 0 is gone.
    for old in range(1, 7):
        text = text.replace(f"binding = {old})", f"binding = {old - 1})")

    # 4. Say what this file is, at the top, since it is generated.
    text = text.replace(
        "// KawPow's mix, as a Vulkan compute shader.",
        "// KawPow's mix, as a Vulkan compute shader - the FAST variant.\n"
        "//\n"
        "// GENERATED from kernel.comp by scripts/gen_kawpow_spec.py. Do not\n"
        "// edit: change kernel.comp, which is the one the correctness gate\n"
        "// checks against the host, and regenerate. Everything except the\n"
        "// program's source and the shape of the round loop is the same text.",
        1)
    # The disclaimer about being the slow one belongs to the other file.
    text = text.replace(
        "// This is the CORRECTNESS version, and it is slow on purpose",
        "// This is the FAST version; kernel.comp is the correctness one")
    print(text)


if __name__ == "__main__":
    main()
